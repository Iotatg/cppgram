def cxx(s):
    out = []
    for ch in s:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\t':
            out.append('\\t')
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append('\\x%02x""' % ord(ch) if ord(ch) < 256 else '\\u%04x' % ord(ch))
    return '"' + ''.join(out) + '"'


