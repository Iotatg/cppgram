import json

def unesc(raw):
    out, i = '', 0
    while i < len(raw):
        if raw[i] == '\\' and i + 1 < len(raw):
            out += {'n': '\n', '\\': '\\', '"': '"', 't': '\t'}.get(raw[i + 1], '\\' + raw[i + 1])
            i += 2
        else:
            out += raw[i]; i += 1
    return out


